#!/usr/bin/env node
// Generates the landing site's copy of these skills: the exact SKILL.md bytes, digests,
// signatures and public key, as one TypeScript module that the skipcalls.com routes serve.
//   node scripts/export-landing.mjs <landing checkout>
// writes <landing>/app/.well-known/agent-skills/_generated/skills.ts. Never edit that file
// by hand: edit skills/, run sign.mjs, commit, export, then ship the landing PR.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { REPOSITORY, ROOT, SIGNATURE_NAMESPACE, SIGNER_IDENTITY, checksumsText, listSkills } from './lib.mjs'

const landing = process.argv[2]
if (!landing) {
  console.error('usage: node scripts/export-landing.mjs <landing checkout>')
  process.exit(1)
}

const status = execFileSync('git', ['status', '--porcelain'], { cwd: ROOT }).toString().trim()
if (status) {
  console.error('commit the skills repo first; the landing module records the source commit')
  process.exit(1)
}
const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: ROOT }).toString().trim()

const read = (p) => readFileSync(join(ROOT, p), 'utf8')
const skills = listSkills().map((s) => ({
  name: s.name,
  description: s.frontmatter.description,
  sha256: s.sha256,
  markdown: s.bytes.toString('utf8'),
  signature: readFileSync(s.sigPath, 'utf8'),
}))
const sums = read('SHA256SUMS')
if (sums !== checksumsText(listSkills())) {
  console.error('SHA256SUMS is stale: run node scripts/sign.mjs')
  process.exit(1)
}

const s = (v) => JSON.stringify(v)
const body = `// GENERATED by ${REPOSITORY}/blob/main/scripts/export-landing.mjs. Do not edit.
// Source of truth: ${REPOSITORY} at commit ${commit}.
// To change a skill: edit it in that repo, sign, commit, export here, ship this file.

export const SKILLS_SOURCE = {
  repository: ${s(REPOSITORY)},
  commit: ${s(commit)},
  install: ${s('npx skills add cail-io/skipcalls-agent-skills')},
} as const

export const SKILLS_SIGNING = {
  format: 'sshsig',
  namespace: ${s(SIGNATURE_NAMESPACE)},
  identity: ${s(SIGNER_IDENTITY)},
  publicKey: ${s(read('keys/skipcalls-skills.pub'))},
  allowedSigners: ${s(read('keys/allowed_signers'))},
} as const

export const SKILLS_CHECKSUMS = ${s(sums)}

export const SKILLS_CHECKSUMS_SIGNATURE = ${s(read('SHA256SUMS.sig'))}

export type GeneratedSkill = {
  name: string
  description: string
  sha256: string
  markdown: string
  signature: string
}

export const GENERATED_SKILLS: readonly GeneratedSkill[] = [
${skills.map((k) => `  {\n    name: ${s(k.name)},\n    description: ${s(k.description)},\n    sha256: ${s(k.sha256)},\n    markdown: ${s(k.markdown)},\n    signature: ${s(k.signature)},\n  },`).join('\n')}
]
`
const outDir = join(landing, 'app', '.well-known', 'agent-skills', '_generated')
mkdirSync(outDir, { recursive: true })
writeFileSync(join(outDir, 'skills.ts'), body)
console.log(`wrote ${join(outDir, 'skills.ts')} (${skills.length} skills, source ${commit.slice(0, 12)})`)
